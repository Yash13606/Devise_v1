"""Own a separate loopback development database; never reuse the system cluster.

Private state lives in .local. Run with the repository's isolated interpreter.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import secrets
import shutil
import socket
import subprocess
import sys
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
STATE = ROOT / ".local"
MARKER = "# Generated by Devise local setup. Local development only."


def validate_port(value: object) -> int:
    try:
        port = int(value)
    except (ValueError, TypeError):
        raise ValueError("Invalid local database port") from None
    if not 1024 <= port <= 65535:
        raise ValueError("Local database port must be between 1024 and 65535")
    return port


def owned_path(root: Path, name: str) -> Path:
    target = (root / name).resolve()
    if not target.is_relative_to(root.resolve()) or target == root.resolve():
        raise ValueError("Refusing path outside the Devise local state directory")
    return target


def load_or_create_config(path: Path, port: int) -> dict:
    port = validate_port(port)
    if path.exists():
        config = json.loads(path.read_text(encoding="utf-8"))
        if config.get("port") != port:
            raise ValueError("Existing local database uses a different port; preserve its configuration")
        for key, user, database in [("admin_dsn", "devise_owner", "devise_local"),
                                    ("runtime_dsn", "devise_app", "devise_local")]:
            url = urlsplit(config.get(key, ""))
            if (url.scheme != "postgresql" or url.hostname != "127.0.0.1" or url.port != port
                    or url.username != user or url.path != "/" + database or not url.password):
                raise ValueError("Refusing non-local database configuration")
        if len(config.get("auth_secret", "")) < 48:
            raise ValueError("Invalid local authentication secret")
        expected = {"test_admin_dsn": config["admin_dsn"].rsplit("/", 1)[0] + "/devise_test",
                    "test_runtime_dsn": config["runtime_dsn"].rsplit("/", 1)[0] + "/devise_test"}
        if any(key in config and config[key] != value for key, value in expected.items()):
            raise ValueError("Refusing non-local test database configuration")
        if any(key not in config for key in expected):
            config.update(expected)
            path.write_text(json.dumps(config, indent=2), encoding="utf-8")
        return config
    path.parent.mkdir(parents=True, exist_ok=True)
    config = {
        "version": 1, "port": port,
        "admin_dsn": f"postgresql://devise_owner:{secrets.token_urlsafe(32)}@127.0.0.1:{port}/devise_local",
        "runtime_dsn": f"postgresql://devise_app:{secrets.token_urlsafe(32)}@127.0.0.1:{port}/devise_local",
        "auth_secret": secrets.token_urlsafe(48),
    }
    config["test_admin_dsn"] = config["admin_dsn"].rsplit("/", 1)[0] + "/devise_test"
    config["test_runtime_dsn"] = config["runtime_dsn"].rsplit("/", 1)[0] + "/devise_test"
    # Exclusive creation prevents concurrent setup from replacing credentials.
    with path.open("x", encoding="utf-8") as handle:
        json.dump(config, handle, indent=2)
    path.chmod(0o600)
    return config


def write_environment(path: Path, config: dict) -> None:
    content = "\n".join([
        MARKER, "APP_ENV=development", "DEVISE_AUTH_MODE=local",
        "DATABASE_URL=" + config["runtime_dsn"],
        "DATABASE_ADMIN_URL=" + config["admin_dsn"],
        "DEVISE_LOCAL_AUTH_SECRET=" + config["auth_secret"],
        "CORS_ORIGINS=http://127.0.0.1:8081,http://localhost:8081",
        "",
    ])
    if path.exists():
        if path.read_text(encoding="utf-8") != content:
            raise ValueError("Refusing to overwrite existing .env.local settings. Preserve or move that file before local setup.")
        return
    with path.open("x", encoding="utf-8") as handle:
        handle.write(content)
    path.chmod(0o600)


def postgres_bin() -> Path:
    configured = os.environ.get("DEVISE_POSTGRES_BIN")
    if configured:
        candidates = [Path(configured)]
    else:
        candidates = [Path(found).parent] if (found := shutil.which("initdb")) else []
        base = Path(os.environ.get("ProgramFiles", "C:/Program Files")) / "PostgreSQL"
        if base.exists():
            candidates += sorted(base.glob("*/bin"), reverse=True)
    for directory in candidates:
        if (directory / ("initdb.exe" if os.name == "nt" else "initdb")).exists():
            return directory
    raise RuntimeError("PostgreSQL binaries not found. Install PostgreSQL or set DEVISE_POSTGRES_BIN. Docker alternative: see planning/LOCAL_SETUP.md.")


def pg_run(binary: Path, args: list[str], *, capture: bool = False) -> subprocess.CompletedProcess:
    # PostgreSQL children can inherit pipe handles on Windows. A real logfile
    # avoids waiting forever for EOF after pg_ctl itself has already exited.
    with (STATE / "setup.log").open("a", encoding="utf-8") as log:
        return subprocess.run([str(binary), *args], cwd=ROOT, check=True,
                              stdout=log if capture else None,
                              stderr=subprocess.STDOUT if capture else None,
                              text=True, timeout=60,
                              creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0)


def start_database(config: dict) -> None:
    directory = postgres_bin()
    data = owned_path(STATE, "postgres")
    pg_ctl = directory / "pg_ctl"
    if os.name == "nt":
        pg_ctl = pg_ctl.with_suffix(".exe")
    if (data / "PG_VERSION").exists():
        state = subprocess.run([str(pg_ctl), "-D", str(data), "status"], capture_output=True)
        if state.returncode == 0:
            print(f"Devise PostgreSQL is running on loopback:{config['port']}.")
            return
    with socket.socket() as probe:
        if probe.connect_ex(("127.0.0.1", config["port"])) == 0:
            raise RuntimeError(f"Port {config['port']} is already occupied by another process; no existing service was changed.")
    if not (data / "PG_VERSION").exists():
        pwfile = owned_path(STATE, "initdb-password")
        try:
            with pwfile.open("x", encoding="utf-8") as handle:
                handle.write(urlsplit(config["admin_dsn"]).password)
            pwfile.chmod(0o600)
            initdb = directory / ("initdb.exe" if os.name == "nt" else "initdb")
            pg_run(initdb, ["-D", str(data), "-U", "devise_owner", "--auth=scram-sha-256",
                            "--pwfile", str(pwfile), "--encoding=UTF8", "--locale=C"], capture=True)
        finally:
            pwfile.unlink(missing_ok=True)
    pg_run(pg_ctl, ["-D", str(data), "-l", str(owned_path(STATE, "postgres.log")),
                    "-o", f"-h 127.0.0.1 -p {config['port']}", "-w", "start"], capture=True)
    print(f"Started separate Devise PostgreSQL on loopback:{config['port']}.")


def bootstrap(config: dict) -> None:
    import psycopg
    from psycopg import sql
    with psycopg.connect(config["admin_dsn"], dbname="postgres", autocommit=True, connect_timeout=5) as conn:
        if not conn.execute("SELECT 1 FROM pg_roles WHERE rolname='devise_app'").fetchone():
            conn.execute(sql.SQL("CREATE ROLE devise_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD {}")
                         .format(sql.Literal(urlsplit(config["runtime_dsn"]).password)))
        for database in ["devise_local", "devise_test"]:
            if not conn.execute("SELECT 1 FROM pg_database WHERE datname=%s", (database,)).fetchone():
                conn.execute(sql.SQL("CREATE DATABASE {} OWNER devise_owner").format(sql.Identifier(database)))
            conn.execute(sql.SQL("REVOKE ALL ON DATABASE {} FROM PUBLIC").format(sql.Identifier(database)))
            conn.execute(sql.SQL("GRANT CONNECT ON DATABASE {} TO devise_app").format(sql.Identifier(database)))
    print("Local database and restricted application role are ready.")


def docker_database(config: dict, command: str) -> None:
    private_env = owned_path(STATE, "compose.env")
    content = f"DEVISE_DB_PORT={config['port']}\nDEVISE_LOCAL_DB_PASSWORD={urlsplit(config['admin_dsn']).password}\n"
    if private_env.exists() and private_env.read_text(encoding="utf-8") != content:
        raise ValueError("Refusing to overwrite different private Docker credentials")
    if not private_env.exists():
        with private_env.open("x", encoding="utf-8") as handle:
            handle.write(content)
        private_env.chmod(0o600)
    args = ["docker", "compose", "--env-file", str(private_env)]
    args += {"start": ["up", "-d", "--wait", "--wait-timeout", "45"], "stop": ["stop"], "status": ["ps"]}[command]
    subprocess.run(args, cwd=ROOT, check=True, timeout=60)


def environment(config: dict) -> dict:
    return {**os.environ, "APP_ENV": "development", "DEVISE_AUTH_MODE": "local",
            "DATABASE_URL": config["runtime_dsn"],
            "DATABASE_ADMIN_URL": config["admin_dsn"],
            "DEVISE_LOCAL_AUTH_SECRET": config["auth_secret"]}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["database", "setup", "stop", "status", "migrate"])
    parser.add_argument("--port", type=int, default=55432)
    parser.add_argument("--provider", choices=["native", "docker"], help="Choose once for a new local database")
    args = parser.parse_args()
    config_path = STATE / "database.json"
    if args.command in {"stop", "status"} and not config_path.exists():
        print("No Devise local database has been initialized.")
        return
    config = load_or_create_config(config_path, args.port)
    provider = config.get("provider", "native")
    if args.provider and args.provider != provider:
        if (STATE / "postgres" / "PG_VERSION").exists() or config.get("provider"):
            raise ValueError("Refusing to switch an existing local database provider; preserve the existing data")
        config["provider"] = provider = args.provider
        config_path.write_text(json.dumps(config, indent=2), encoding="utf-8")
    if args.command in {"status", "stop"}:
        if provider == "docker":
            docker_database(config, "stop" if args.command == "stop" else "status")
            return
        directory = postgres_bin()
        pg_ctl = directory / ("pg_ctl.exe" if os.name == "nt" else "pg_ctl")
        data = owned_path(STATE, "postgres")
        if args.command == "stop":
            pg_run(pg_ctl, ["-D", str(data), "-m", "fast", "-w", "stop"], capture=True)
            print("Stopped Devise's local database; all data retained.")
        else:
            result = subprocess.run([str(pg_ctl), "-D", str(data), "status"], capture_output=True)
            print("Devise PostgreSQL: " + ("running" if result.returncode == 0 else "stopped"))
        return
    # Validate settings before starting any service; never overwrite owner settings.
    write_environment(ROOT / ".env.local", config)
    if provider == "docker":
        docker_database(config, "start")
    else:
        start_database(config)
    bootstrap(config)
    if args.command in {"setup", "migrate"}:
        env = environment(config)
        for command in ["migrate", "seed-local"] if args.command == "setup" else ["migrate"]:
            subprocess.run([sys.executable, "-m", "api.manage", command], cwd=ROOT, env=env, check=True)
        print("Local setup complete. Start: npm run dev:local. No cloud login or database was configured.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, RuntimeError) as exc:
        print(str(exc), file=sys.stderr)
        sys.exit(1)
    except subprocess.CalledProcessError as exc:
        # Subprocess environment can contain credentials. Do not dump it or DSNs.
        print(f"Local setup subprocess failed (exit {exc.returncode}). Check .local logs and installed dependencies.", file=sys.stderr)
        sys.exit(1)
    except subprocess.TimeoutExpired:
        print("Local service startup exceeded its deadline. No existing data was removed.", file=sys.stderr)
        sys.exit(1)
